// arcade-fights.mjs — the 游戏厅's 斗法 table (worlds/jiuding/levels/kapai.json): every fight of 卷一 as the
// story deals it the first time a player meets it — the realm, the hand, the gear and who stands with him at
// that point of the road (tools/story-fights.mjs FIGHTS · setupOf), the foe's brief as the story's door gives it
// (rules/look.mjs duelBrief), and the 丹囊 the story lets him carry (two pills; none at the 三试, before the
// root test). The page only begins and plays them (games/kapai.js); nothing here runs in a browser.
//
//   node tools/arcade-fights.mjs           write it
//   node tools/arcade-fights.mjs --check   exit 1 if the file is stale (tests/arcade-kapai.test.mjs runs it)
import fs from 'node:fs';
import { content, FIGHTS, gameOf, keyOf, NOW, roadState, setupOf, TWO_PILLS } from './story-fights.mjs';
import { duelBrief } from '../scripts/rules/look.mjs';
import { huiLabel, huiNow, huiOrder } from '../scripts/rules/hui.mjs';

export const OUT = new URL('../worlds/jiuding/levels/kapai.json', import.meta.url);
const LANGS = ['zh', 'en'];
const both = (fn) => Object.fromEntries(LANGS.map((l) => [l, fn(l)]));
const pick = (v, l) => (v && typeof v === 'object' ? v[l] ?? v.zh : v) ?? null;
/* The one line on its tile: the look's first clause (creatures.json `look`). */
const firstClause = (s) => String(s ?? '').split(/(?<=[。！？])|(?<=[.!?])\s/)[0].trim().replace(/[；;，,]$/, '');
const poolOf = (id) => Object.values(content.places).map((p) => p.pools?.[id]).find(Boolean) ?? null;

/* The foe as the door shows it, in one language: name, its 试's goal, the lines it says; the stake (a scene's
   回 · a pool's stretch of country). */
function briefIn(f, lang) {
  const st = { ...roadState(f), lang };
  const b = duelBrief(content, st, gameOf(f), NOW, { door: true });
  const pool = f.pool ? poolOf(f.pool) : null;
  return { creature: b.creature, says: b.says ?? null, stake: pool ? pick(pool.name, lang) : b.stake ?? null };
}

function rowOf(f) {
  const c = content.creatures.find?.((x) => x.id === f.id) ?? content.creatures.creatures?.find((x) => x.id === f.id) ?? {};
  const hui = huiNow(content, roadState(f));
  const setup = setupOf(f, { pills: f.nopills ? null : TWO_PILLS });
  delete setup.seed; // each deal its own (games/kapai.js)
  return {
    key: keyOf(f), id: f.id, story: !f.pool, hui, art: c.art ?? null,
    name: both((l) => pick(c.name, l)), hint: both((l) => firstClause(pick(c.look, l))),
    brief: both((l) => briefIn(f, l)), setup,
  };
}

export function table() {
  const seen = new Set(), fights = [];
  for (const f of FIGHTS) {
    if (f.reach === false || seen.has(keyOf(f))) continue;
    seen.add(keyOf(f));
    fights.push(rowOf(f));
  }
  // By the book's order: the 回 first, the story's fights before a pool's beasts within it.
  const at = (r) => huiOrder(content, r.hui);
  fights.sort((a, b) => at(a) - at(b) || Number(b.story) - Number(a.story));
  const huis = [...new Set(fights.map((r) => r.hui))].map((id) => ({ id, label: both((l) => huiLabel(content, id, l, 'short')) }));
  const pills = Object.fromEntries(content.items.items.filter((i) => i.effect?.fight).map((i) => [i.id, { name: i.name, ...(i.art ? { art: i.art } : {}) }]));
  return { _about: 'Generated by tools/arcade-fights.mjs from tools/story-fights.mjs FIGHTS — never edit by hand. The 游戏厅\'s 斗法 (games/kapai.js): every fight of 卷一 as the road deals it at its first meeting.', huis, pills, fights };
}

export const text = () => `${JSON.stringify(table(), null, 1)}\n`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) { if (now !== text()) { console.error('levels/kapai.json is stale: node tools/arcade-fights.mjs'); process.exit(1); } }
  else { fs.writeFileSync(OUT, text()); console.log(`wrote ${OUT.pathname} (${table().fights.length} fights)`); }
}
