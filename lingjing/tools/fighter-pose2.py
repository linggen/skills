#!/usr/bin/env python3
"""fighter-pose2.py — 格斗's pose sketches, second cut (2026-11-10, Hanli: 「现在画出来的拳脚长短感觉不太合理」): a mannequin
in a real body's proportions, its key poses from motion capture where a take exists, the strike's reach checked against
the rules, and every painting checked against its sketch (`obey`, the gate a full repaint goes through).

    python3 tools/fighter-pose2.py mocap  <who> <takes-dir>          the key poses' angles from the takes (→ fighter-poses-v2.json)
    python3 tools/fighter-pose2.py sketch <who> <raw> [--strip out.jpg] the sketches (<raw>/v2-<frame>.png) + a strip of them
    python3 tools/fighter-pose2.py reach  <who> <raw>                 the rule's reach against the sketch's fist / foot
    python3 tools/fighter-pose2.py paint  <who> <raw> [--only a,b] [--seeds 1] [--master]   one FLUX batch, nice -n 15
    python3 tools/fighter-pose2.py obey   <who> <raw> [--pick f=seed,…]  each painting's reach against its sketch's

Why a second cut. The first sketch (tools/fighter-frames.py) drew a body 810 px tall with legs 0.47 of it, arms 0.34 and a
head of 1/6.5 — then the painting is scaled about 1.26× up to the master's height, so every limb came out ~11 % short of
a real one; and its hand-typed key poses never straightened the limb at the strike. Here the body is 7.4 heads (crown at
990 px over the ground, the bun to ~1024 — the master's own painted height, so the sketch and the painting share one
scale and one place: feet on PGROUND, the hips' column at HIPX). The lengths, as shares of the height H (Drillis &
Contini's segment table, the one Winter's *Biomechanics* reprints): head 0.135, shoulder to chin 0.05, hip joint to
shoulder 0.288, thigh 0.245, shin 0.246, ankle to sole 0.039, upper arm 0.186, forearm 0.146, wrist to knuckles 0.06,
foot 0.152. Arm (to the knuckles) : leg (to the sole) = 0.39 : 0.53.

The poses: tools/fighter-poses-v2.json, per fighter — `frames` (each frame's angles in fighter-poses' own terms: lean,
legF/legB/armF/armB as [upper, lower] degrees from straight down, positive toward the facing side; F the near side; `shF`
/ `shB` a shoulder's own shift forward, as a share of H, from the take; `sword` the blade's angle from straight down;
`src` where it came from) and `clips`. A frame with `take` is regenerated by `mocap` from the CMU Graphics Lab Motion
Capture Database (tools/fighter-mocap.py: its terms, and that the takes stay local); a frame without one is authored here
from plain martial-arts knowledge. `edit` lays a change on the take (a kick lowered to the waist), named in `src`.

The reach (core.js): a blow lands when the two anchors (each fighter's feet) are `reach` units apart (the 上步's `lunge`
moves the anchor during the startup, so a frame never paints the step); its fist or foot then touches her front, GAP/2
units before her anchor. On the sheet a fighter stands 245 units for `stand` sheet pixels (draw.js makeSheet), a sheet
pixel is 1/SCALE painting pixels: 1 unit = stand / 245 / 0.42 ≈ 4.18 painting px for 秦雁. `limb` is a hurtbox (how far
her blow reaches his limb), not where his fist is.
"""
import argparse, importlib.util, json, math, os, subprocess, sys
from pathlib import Path
import numpy as np
from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
def _load(name, file):
  s = importlib.util.spec_from_file_location(name, HERE / file); m = importlib.util.module_from_spec(s); s.loader.exec_module(m)
  return m
FF = _load('fighter_frames', 'fighter-frames.py')
POSES2 = HERE / 'fighter-poses-v2.json'
SHEETS = ROOT / 'worlds' / 'jiuding' / 'art' / 'games' / 'fighter'

W, CH = FF.W, FF.H                     # the painting (768 × 1152), wider per frame by `width`
GROUND, HIPX = FF.PGROUND, FF.HIPX     # the sketch stands where the master's painting stands
HT = 990                               # crown over the ground (the bun reaches ~1024)
SH = dict(head=0.135, neck=0.05, torso=0.288, thigh=0.245, shin=0.246, ankle=0.039, upper=0.186, fore=0.146, fist=0.06, foot=0.152)
L = {k: v * HT for k, v in SH.items()}
UNITS_H = 245                          # draw.js makeSheet: the standing figure is 245 units tall
GAP = 58                               # core.js GAP: the least distance between two bodies (each front GAP/2 off its anchor)
PAPER, INK, FAR, ROBE = (238, 230, 212, 255), (40, 40, 40, 255), (110, 110, 110, 255), (165, 178, 192, 255)
EDIT_STYLE = FF.EDIT_STYLE
SWORD = 290                            # the jian as 秦雁's master paints it (hand to tip, painting px)


def poses():
  return json.loads(POSES2.read_text())


# ── the mannequin ───────────────────────────────────────────────────────────────────────────────────────────────────
def at(o, a, l):
  r = math.radians(a)
  return (o[0] + math.sin(r) * l, o[1] + math.cos(r) * l)


def joints(p):
  """The pose's joints (painting px): built from the hips, then set down so the lowest sole is on GROUND and the anchor
  (both feet's middle when both are down, else the planted foot) is on HIPX + `dx`."""
  hip = (0.0, 0.0)
  lean = math.radians(p.get('lean', 0))
  up = (math.sin(lean), -math.cos(lean))
  sh = (hip[0] + up[0] * L['torso'], hip[1] + up[1] * L['torso'])
  hd = math.radians(p.get('lean', 0) + p.get('head', 0))
  chin = (sh[0] + math.sin(hd) * L['neck'], sh[1] - math.cos(hd) * L['neck'])
  head = (chin[0] + math.sin(hd) * L['head'] / 2, chin[1] - math.cos(hd) * L['head'] / 2)
  j = {'hip': hip, 'sh': sh, 'chin': chin, 'head': head}
  for k, s in (('legF', 'hpF'), ('legB', 'hpB')):
    a = p[k]; o = (hip[0] + p.get(s, 0) * HT, hip[1]); kn = at(o, a[0], L['thigh']); an = at(kn, a[1], L['shin'])
    j[k] = (o, kn, an)
  # planted feet: every foot within a hand of the lowest (or the frame's own `planted`) is set on one ground line by
  # bending its knee (two-bone IK, the knee kept on its side) — a take's two feet never land on one line exactly
  low = max(j[k][2][1] for k in ('legF', 'legB'))
  planted = p.get('planted') or [k for k in ('legF', 'legB') if low - j[k][2][1] < 90]
  for k in planted:
    o, kn, an = j[k]
    j[k] = (o,) + ik(o, kn, (an[0], low))
  for k in ('legF', 'legB'):
    j[k + 'Toe'] = foot_points(j[k][2], p[k][1], p.get(k + 'Foot'))
  for k, s in (('armF', 'shF'), ('armB', 'shB')):
    a = p[k]; o = (sh[0] + p.get(s, 0) * HT, sh[1])
    el = at(o, a[0], L['upper']); wr = at(el, a[1], L['fore']); fi = at(wr, a[1], L['fist'] * 0.55)
    j[k] = (o, el, wr); j[k + 'Fist'] = fi
  # set down: the lowest sole on GROUND
  low = max(pt[1] for k in planted for pt in j[k + 'Toe'])
  ax = np.mean([j[k][2][0] for k in planted])
  dx, dy = HIPX + p.get('dx', 0) - ax, GROUND - low
  mv = lambda pt: (pt[0] + dx, pt[1] + dy)
  out = {}
  for k, v in j.items():
    out[k] = tuple(mv(q) for q in v) if isinstance(v[0], tuple) else mv(v)
  out['anchor'] = (HIPX + p.get('dx', 0), GROUND)
  if p.get('sword') is not None:
    out['tip'] = at(out['armFFist'], p['sword'], SWORD)
  return out


def ik(o, kn, an):
  """Knee and ankle for a leg from hip `o` to the ankle `an` (pulled in along the line if out of reach), the knee on the
  side the given knee `kn` was."""
  a, b = L['thigh'], L['shin']
  dx, dy = an[0] - o[0], an[1] - o[1]; dd = math.hypot(dx, dy)
  if dd > a + b - 1:
    k = (a + b - 1) / dd; an = (o[0] + dx * k, o[1] + dy * k); dx, dy, dd = an[0] - o[0], an[1] - o[1], a + b - 1
  ca = (a * a + dd * dd - b * b) / (2 * a * dd); th = math.acos(max(-1, min(1, ca)))
  base = math.atan2(dy, dx)
  side = 1 if (dx * (kn[1] - o[1]) - dy * (kn[0] - o[0])) > 0 else -1
  k2 = (o[0] + a * math.cos(base + side * th), o[1] + a * math.sin(base + side * th))
  return k2, an


def foot_points(an, shin_a, foot_a=None):
  """The foot's outline: heel, sole under the ankle, toe — a foot flat (toe forward) unless `foot_a` turns it."""
  fa = 90 if foot_a is None else foot_a           # the foot's direction from straight down (90: forward, flat)
  heel = at(an, fa + 180 - 20, L['ankle'] * 1.2)
  toe = at(an, fa - 12, L['foot'] * 0.78)
  sole = at(an, 0 if foot_a is None else fa - 90, L['ankle'])
  return (heel, sole, toe)


def width_of(p, j=None):
  """The canvas: the painting's 768, wider (in 16s) when a fist, foot or blade reaches past it."""
  j = j or joints(p)
  xs = [q[0] for v in j.values() for q in (v if isinstance(v[0], tuple) else (v,))]
  return max(W, p.get('width', 0), int(math.ceil((max(xs) + 90) / 16) * 16))


def sketch(p, out=None, robe=True):
  j = joints(p)
  w = width_of(p, j)
  im = Image.new('RGBA', (w, CH), (0, 0, 0, 0))
  d = ImageDraw.Draw(im)
  def seg(pts, w0, w1, col):  # a tapered limb, round at its joints
    for a, b, wa, wb in zip(pts, pts[1:], np.linspace(w0, w1, len(pts))[:-1], np.linspace(w0, w1, len(pts))[1:]):
      ang = math.atan2(b[1] - a[1], b[0] - a[0]); nx, ny = -math.sin(ang), math.cos(ang)
      d.polygon([(a[0] + nx * wa / 2, a[1] + ny * wa / 2), (b[0] + nx * wb / 2, b[1] + ny * wb / 2),
                 (b[0] - nx * wb / 2, b[1] - ny * wb / 2), (a[0] - nx * wa / 2, a[1] - ny * wa / 2)], fill=col)
      for c, r in ((a, wa / 2), (b, wb / 2)):
        d.ellipse([c[0] - r, c[1] - r, c[0] + r, c[1] + r], fill=col)
  def leg(k, col):
    hip, kn, an = j[k]
    seg([hip, kn, an], 0.075 * HT, 0.045 * HT, col)
    d.polygon(list(j[k + 'Toe']) + [an], fill=col)
  def arm(k, col):
    o, el, wr = j[k]
    seg([o, el, wr], 0.042 * HT, 0.032 * HT, col)
    f = j[k + 'Fist']; r = 0.026 * HT
    d.ellipse([f[0] - r, f[1] - r, f[0] + r, f[1] + r], fill=col)
  leg('legB', FAR)
  if robe:
    robe_poly(d, j)
  raised = lambda k: GROUND - max(pt[1] for pt in j[k + 'Toe']) > 60
  if raised('legF') or not robe:
    leg('legF', INK)
  arm('armB', FAR)
  # the torso: a tapered column, chest deeper than the waist
  seg([j['hip'], j['sh']], 0.10 * HT, 0.125 * HT, INK)
  seg([j['sh'], j['chin']], 0.05 * HT, 0.05 * HT, INK)
  hx, hy = j['head']; rh = L['head'] / 2
  d.ellipse([hx - rh * 0.82, hy - rh, hx + rh * 0.82, hy + rh], fill=INK)
  if not raised('legF') and robe:
    # a grounded near leg shows only below the hem: its foot
    d.polygon(list(j['legFToe']) + [j['legF'][2]], fill=INK)
  arm('armF', INK)
  if 'tip' in j:
    d.line([j['armFFist'], j['tip']], fill=(90, 90, 90, 255), width=10)
  bg = Image.new('RGBA', (w, CH), PAPER)
  bg.alpha_composite(im)
  if out:
    bg.convert('RGB').save(out)
  return bg, j


def robe_poly(d, j):
  """The robe from the waist: to the hem a hand above the grounded feet, draped under a raised thigh."""
  hip = j['hip']; lean = j['sh'][0] - hip[0]
  wst = [(hip[0] - 0.06 * HT + lean * 0.25, hip[1] - 0.06 * HT), (hip[0] + 0.06 * HT + lean * 0.25, hip[1] - 0.06 * HT)]
  pts = list(wst)
  for k in ('legF', 'legB'):
    _, kn, an = j[k]
    if GROUND - an[1] < 80:
      hem = GROUND - 0.05 * HT
      pts += [(kn[0], kn[1]), (an[0] - 0.07 * HT, hem), (an[0] + 0.08 * HT, hem)]
    else:  # a raised leg: the cloth hangs from its thigh
      mid = ((hip[0] + kn[0]) / 2, (hip[1] + kn[1]) / 2)
      pts += [mid, (mid[0], min(GROUND - 0.05 * HT, mid[1] + 0.14 * HT))]
  hull = convex(pts)
  d.polygon(hull, fill=ROBE)


def convex(pts):
  pts = sorted(set(pts))
  if len(pts) < 3:
    return pts
  cross = lambda o, a, b: (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
  lo, hi = [], []
  for p in pts:
    while len(lo) >= 2 and cross(lo[-2], lo[-1], p) <= 0: lo.pop()
    lo.append(p)
  for p in reversed(pts):
    while len(hi) >= 2 and cross(hi[-2], hi[-1], p) <= 0: hi.pop()
    hi.append(p)
  return lo[:-1] + hi[:-1]


# ── the reach ──────────────────────────────────────────────────────────────────────────────────────────────────────
def unit_px(who):
  """Painting px per rule unit: the sheet's standing height (stand sheet px = 245 units) over SCALE."""
  stand = json.loads((SHEETS / f'{who}.json').read_text())['stand']
  return stand / UNITS_H / FF.SCALE


def rules():
  """core.js ME's moves, read from the source (no node needed): {move: {reach, lunge, limb}}."""
  src = (ROOT / 'scripts' / 'games' / 'fighter' / 'core.js').read_text()
  out = {}
  for k in ('light', 'hpunch', 'heavy', 'lkick', 'cheavy', 'clkick'):
    import re
    m = re.search(r'\n  ' + k + r': \{([^}]*)\}', src)
    out[k] = {f: float(v) for f, v in re.findall(r'(reach|lunge|limb): (\d+)', m.group(1))}
  return out


def strike_end(p, j):
  """The striking fist or foot (the frame's `strike`: armF/armB/legF/legB) — its furthest point toward the facing side."""
  k = p.get('strike', 'armF')
  if k.startswith('arm'):
    f = j[k + 'Fist']; return (f[0] + 0.026 * HT, f[1])
  pts = list(j[k + 'Toe']) + [j[k][2]]
  return max(pts, key=lambda q: q[0])


# ── obedience: the painting's reach against its sketch's ─────────────────────────────────────────────────────────────
def ink_reach(rgba, band, scale=1.0):
  """A figure's reach toward the facing side (right): from its planted feet (the mean column of the ink in the lowest
  4 % of the figure) to the furthest ink inside the height `band` (y0, y1 painting px over the soles); and back the
  other way, so a blade held out in the band where the sketch has none shows as its own error. `scale` corrects a
  painting that came out bigger or smaller than its master. Returns (front, back) in px, or None."""
  a = np.asarray(rgba.getchannel('A')) > 128
  ys = np.nonzero(a.any(1))[0]
  if not len(ys):
    return None
  sole = int(ys.max()); top = int(ys.min())
  foot = a[max(top, sole - int(0.04 * (sole - top))):sole + 1]
  fx = float(np.nonzero(foot.any(0))[0].mean())
  y0, y1 = int(sole - band[1] * scale), int(sole - band[0] * scale)
  rows = a[max(0, y0):max(0, y1)]
  cols = np.nonzero(rows.any(0))[0]
  if not len(cols):
    return None
  return (float(cols.max() - fx) / scale, float(fx - cols.min()) / scale)


def sketch_mask(p):
  im, j = sketch(p)
  arr = np.asarray(im.convert('RGB')).astype(int)
  m = (np.abs(arr - np.array(PAPER[:3])).max(2) > 18).astype(np.uint8) * 255
  return Image.fromarray(np.dstack([arr.astype(np.uint8), m]).astype(np.uint8), 'RGBA'), j


def band_of(p, j):
  """The height band the strike is measured in: the striking end's height ± 0.09 H (over the ground)."""
  e = strike_end(p, j); h = GROUND - e[1]
  return (max(0, h - 0.09 * HT), h + 0.09 * HT)


def obey(p, painting, scale=1.0, tol=0.12):
  """One painted frame against its sketch: (ok, painted (front, back), sketch (front, back), front ratio). The gate for
  a repaint. The edit keeps the master's size (the sketch is drawn at it), so `scale` stays 1 unless a painting is
  known to have come out bigger; the hair's measure (fighter-frames head_size) is too noisy across poses to set it
  (秦雁's 2026-11-10 sample: 123–184 px for one head)."""
  sk, j = sketch_mask(p)
  band = band_of(p, j)
  want = ink_reach(sk, band)
  keyed = FF.key(painting) if not isinstance(painting, Image.Image) else painting
  got = ink_reach(keyed, band, scale)
  if not want or not got:
    return False, got, want, None
  r = got[0] / want[0]
  return abs(r - 1) <= tol, got, want, r


# ── mocap → angles ─────────────────────────────────────────────────────────────────────────────────────────────────
def from_takes(who, takes):
  MC = _load('fighter_mocap', 'fighter-mocap.py')
  data = poses(); spec = data[who]
  cache = {}
  for name, f in spec['frames'].items():
    t = f.get('take')
    if not t:
      continue
    subj = t['amc'].split('_')[0]
    asf = cache.setdefault(subj, MC.read_asf(Path(takes) / f'{subj}.asf'))
    fr = cache.setdefault(t['amc'], MC.read_amc(Path(takes) / t['amc']))
    fj = MC.joints(asf, fr[t['axisFrame']])
    fwd = MC.plane(fj, t['face'])
    pose, q = angles_on(MC, asf, fr[t['frame']], fwd, t['near'])
    pose.update(f.get('edit', {}))
    keep = {k: v for k, v in f.items() if k not in pose}
    spec['frames'][name] = {**pose, **keep}
    print(name, json.dumps(pose))
  POSES2.write_text(json.dumps(data, ensure_ascii=False, indent=1) + '\n')


def angles_on(MC, asf, frame, fwd, near):
  j = MC.joints(asf, frame)
  q = MC.project(j, fwd)
  f, b = near, 'l' if near == 'r' else 'r'
  hipc = (q['lhip'] + q['rhip']) / 2; shc = (q['lsh'] + q['rsh']) / 2
  leg_m = np.linalg.norm(q['lknee'] - q['lhip']) + np.linalg.norm(q['lankle'] - q['lknee'])
  d = shc - hipc
  lean = math.degrees(math.atan2(d[0], d[1]))
  two = lambda a, m, e: [round(MC.ang(q[a], q[m])), round(MC.ang(q[m], q[e]))]
  # a shoulder's shift along the line across the chest, past the torso's own column
  # metres → shares of H by the leg's length (the take's thigh + shin against SH's)
  shift = lambda s: round(float((q[s] - shc)[0]) / leg_m * (SH['thigh'] + SH['shin']), 3)
  shift2 = lambda s: round(float((q[s] - hipc)[0]) / leg_m * (SH['thigh'] + SH['shin']), 3)
  return {'lean': round(lean), 'legF': two(f + 'hip', f + 'knee', f + 'ankle'), 'legB': two(b + 'hip', b + 'knee', b + 'ankle'),
          'armF': two(f + 'sh', f + 'elb', f + 'wri'), 'armB': two(b + 'sh', b + 'elb', b + 'wri'),
          'shF': shift(f + 'sh'), 'shB': shift(b + 'sh'), 'hpF': shift2(f + 'hip'), 'hpB': shift2(b + 'hip'),
          'head': round(math.degrees(math.atan2((q['head'] - q['neck'])[0], (q['head'] - q['neck'])[1]))) - round(lean)}, q


# ── commands ──────────────────────────────────────────────────────────────────────────────────────────────────────
def cmd_sketch(who, raw, strip):
  spec = poses()[who]; raw.mkdir(parents=True, exist_ok=True)
  ims = []
  for n, p in spec['frames'].items():
    im, j = sketch(p, raw / f'v2-{n}.png')
    ims.append((n, im, j))
  if strip:
    hgt = 420; k = hgt / CH
    tiles = [(n, im.resize((round(im.width * k), hgt), Image.LANCZOS), j) for n, im, j in ims]
    out = Image.new('RGB', (sum(t[1].width for t in tiles) + 8 * len(tiles), hgt + 24), (250, 246, 238))
    d = ImageDraw.Draw(out); x = 0
    for n, t, j in tiles:
      out.paste(t, (x, 0)); d.text((x + 6, hgt + 6), n, fill=(0, 0, 0))
      ax = j['anchor'][0] * k + x; d.line([(ax, hgt - 10), (ax, hgt)], fill=(200, 30, 30), width=2)
      x += t.width + 8
    out.save(strip, quality=86)
    print('strip', strip)


def reach_table(who):
  spec = poses()[who]; R = rules(); u = unit_px(who)
  rows = []
  for n, p in spec['frames'].items():
    if not p.get('move') or not p.get('strike') or not p.get('hitFrame'):
      continue
    m = R[p['move']]
    j = joints(p); e = strike_end(p, j)
    rule = m['reach'] * u; front = GAP / 2 * u
    rows.append({'frame': n, 'move': p['move'], 'reach_u': m['reach'], 'rule_px': round(rule), 'foe_front_px': round(front),
                 'target_px': round(rule - front), 'sketch_px': round(e[0] - j['anchor'][0]),
                 'sketch_u': round((e[0] - j['anchor'][0]) / u, 1), 'height_px': round(GROUND - e[1])})
  return rows, u


def cmd_paint(who, raw, only, seeds, master):
  data = poses(); spec = data[who]; old = FF.POSES[who]
  raw.mkdir(parents=True, exist_ok=True)
  ms = old['master']; mpng = raw / f"{who}-master-s{ms['seed']}.png"
  jobs = []
  if master or not mpng.exists():
    jobs.append({'seed': ms['seed'], 'prompt': ms['words'], 'out': str(mpng)})
  for n, p in spec['frames'].items():
    if only and n not in only:
      continue
    sk = raw / f'v2-{n}.png'; sketch(p, sk)
    for sd in seeds:
      jobs.append({'seed': sd, 'out': str(raw / f'{who}-v2-{n}-s{sd}.png'), 'refs': [str(mpng), str(sk)], 'width': width_of(p),
                   'prompt': f"Repaint {old['who']} in the pose of the second image: {p['words']} {EDIT_STYLE}"})
  env = dict(os.environ, HF_HOME=str(Path.home() / '.linggen/models/hf-hub'), HF_HUB_OFFLINE='1')
  wait_quiet()
  print(who, len(jobs), 'paintings', flush=True)
  r = subprocess.run(['nice', '-n', '15', str(FF.PY), str(HERE / 'fighter-flux.py')], input=json.dumps({'model': FF.MODEL, 'jobs': jobs}),
                     text=True, env=env, stdout=subprocess.PIPE)
  print(r.stdout[-300:])
  if r.returncode:
    raise SystemExit(r.returncode)


def wait_quiet(poll=5):
  """Never two FLUX at once on this Mac, and never under a heavy load: wait for any fighter-flux to end and the load to
  fall under 75 % of the cores."""
  import time
  while True:
    busy = subprocess.run(['pgrep', '-f', 'fighter-flux'], stdout=subprocess.PIPE, text=True).stdout.split()
    load = os.getloadavg()[0]
    if not busy and load < (os.cpu_count() or 8) * 0.75:
      return
    if int(time.time()) % 300 < poll:
      print(time.strftime('%H:%M'), 'waiting: flux', busy, 'load', round(load, 1), flush=True)
    time.sleep(poll)


def gate(who, raw, only, tries=(1, 2, 3)):
  """Paint, check, repaint: each frame's first seed whose reach is within 12 % of its sketch's is kept; a frame that
  never passes keeps its closest seed and is named. One FLUX batch per try. Writes <raw>/gate.json."""
  spec = poses()[who]
  names = [n for n in spec['frames'] if not only or n in only]
  log, todo = {}, list(names)
  for sd in tries:
    if not todo:
      break
    cmd_paint(who, raw, set(todo), [sd], False)
    for n in list(todo):
      ok, got, want, r = obey(spec['frames'][n], raw / f'{who}-v2-{n}-s{sd}.png')
      log.setdefault(n, []).append({'seed': sd, 'ok': ok, 'ratio': None if r is None else round(r, 3)})
      print(f'{n:8} s{sd} {"ok" if ok else "OFF"} {r and round(r, 3)}', flush=True)
      if ok:
        todo.remove(n)
  kept = {}
  for n, tr in log.items():
    best = next((t for t in tr if t['ok']), None) or min(tr, key=lambda t: abs((t['ratio'] or 0) - 1))
    kept[n] = {**best, 'tries': tr}
  (raw / 'gate.json').write_text(json.dumps(kept, indent=1) + '\n')
  print('gate: kept', {n: v['seed'] for n, v in kept.items()}, 'still off', [n for n, v in kept.items() if not v['ok']])
  return kept


def cmd_obey(who, raw, pick):
  spec = poses()[who]; old = FF.POSES[who]
  res = {}
  for n, p in spec['frames'].items():
    sd = pick.get(n, p.get('seed', 1)); png = raw / f'{who}-v2-{n}-s{sd}.png'
    if not png.exists():
      continue
    ok, got, want, r = obey(p, png)
    res[n] = {'seed': sd, 'ok': ok, 'ratio': None if r is None else round(r, 3), 'painted': got and [round(v) for v in got],
              'sketch': want and [round(v) for v in want]}
    print(f"{n:10} s{sd}  {'ok  ' if ok else 'OFF '} ratio {res[n]['ratio']}  painted {res[n]['painted']}  sketch {res[n]['sketch']}")
  return res


def placed_new(png, p):
  """A new painting off its paper, at the sheet's scale, with its anchor: the sketch's anchor column, moved by how far
  the painted feet sit from the sketch's (both by `ink_reach`'s foot measure), its soles on the ground."""
  keyed = FF.key(png)
  a = np.asarray(keyed.getchannel('A')) > 128
  ys = np.nonzero(a.any(1))[0]; sole, top = int(ys.max()), int(ys.min())
  foot = a[max(top, sole - int(0.04 * (sole - top))):sole + 1]
  fx = float(np.nonzero(foot.any(0))[0].mean())
  sk, j = sketch_mask(p)
  sa = np.asarray(sk.getchannel('A')) > 128; sy = np.nonzero(sa.any(1))[0]
  sfoot = sa[sy.max() - int(0.04 * (sy.max() - sy.min())):sy.max() + 1]
  sfx = float(np.nonzero(sfoot.any(0))[0].mean())
  ax = j['anchor'][0] + (fx - sfx)
  small = keyed.resize((round(keyed.width * FF.SCALE), round(keyed.height * FF.SCALE)), Image.LANCZOS)
  box = small.getchannel('A').point(lambda v: 255 if v > 10 else 0).getbbox()
  return small.crop(box), (ax * FF.SCALE - box[0], sole * FF.SCALE - box[1])


def compare(who, raw, out, pairs, pick, font=None):
  """Old against new, clip by clip, on one ground line at the sheet's scale: OLD (cut from the shipped sheet) above,
  NEW (the paintings of this cut) below with each sketch small beside its frame."""
  from PIL import ImageFont
  F = lambda sz: ImageFont.truetype(font, sz) if font else ImageFont.load_default()
  meta = json.loads((SHEETS / f'{who}.json').read_text()); sheet = Image.open(SHEETS / f'{who}.webp').convert('RGBA')
  spec = poses()[who]
  cell, gap_h, lab = 330, 470, 330
  rows = []
  for title, old_clip, old_label, new_clip, new_label in pairs:
    olds = meta['clips'][old_clip]['frames'] if old_clip else []
    news = spec['clips'][new_clip]['frames']
    width = lab + cell * max(len(olds), len(news)) * 1.0 + 330 * len(news)
    row = Image.new('RGB', (int(width), gap_h * 2 + 50), (236, 226, 204)); d = ImageDraw.Draw(row)
    d.text((16, 10), title, fill=(60, 20, 10), font=F(34))
    for r, (label, names) in enumerate(((old_label, olds), (new_label, news))):
      g = 50 + gap_h * (r + 1) - 40
      d.line([(lab - 20, g), (row.width, g)], fill=(170, 60, 40), width=2)
      for i, ln in enumerate(label.split('\n')):
        d.text((16, g - gap_h / 2 + i * 34), ln, fill=(30, 30, 30), font=F(26))
      x = lab
      for n in names:
        if r == 0:
          f = meta['frames'][n]; rc = f['rect']; im = sheet.crop((rc[0], rc[1], rc[0] + rc[2], rc[1] + rc[3])); anc = f['anchor']
        else:
          p = spec['frames'][n]; sd = pick.get(n, p.get('seed', 1))
          png = raw / f'{who}-v2-{n}-s{sd}.png'
          if not png.exists():
            x += cell; continue
          im, anc = placed_new(png, p)
        ax = x + 110
        row.paste(im, (int(ax - anc[0]), int(g - anc[1])), im)
        d.line([(ax, g), (ax, g + 10)], fill=(200, 30, 30), width=3)
        if r == 1:
          sk, _ = sketch(spec['frames'][n]); sk = sk.convert('RGB'); sk.thumbnail((150, 225))
          sx = int(ax - anc[0] + im.width + 12); row.paste(sk, (sx, int(g - sk.height)))
          d.text((ax - 40, g + 12), n, fill=(60, 60, 60), font=F(18))
          x = max(x + cell, sx + sk.width + 30)
        else:
          d.text((ax - 40, g + 12), n, fill=(60, 60, 60), font=F(18))
          x = max(x + cell, int(ax - anc[0] + im.width + 30))
      if not names:
        d.text((lab, g - 60), '（旧图里没有这一招：秦雁原来只用剑）', fill=(120, 60, 40), font=F(26))
    rows.append(row)
  W2 = max(r.width for r in rows)
  big = Image.new('RGB', (W2, sum(r.height for r in rows)), (236, 226, 204)); y = 0
  for r in rows:
    big.paste(r, (0, y)); y += r.height
  big.save(out, quality=84)
  print('compare', out, big.size)


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument('cmd', choices=['mocap', 'sketch', 'reach', 'paint', 'obey', 'compare', 'gate'])
  ap.add_argument('who'); ap.add_argument('dir')
  ap.add_argument('--strip', default=''); ap.add_argument('--only', default=''); ap.add_argument('--seeds', default='1')
  ap.add_argument('--master', action='store_true'); ap.add_argument('--pick', default='')
  ap.add_argument('--out', default=''); ap.add_argument('--pairs', default='', help='a JSON list of [title, old clip|null, old label, new clip, new label]')
  ap.add_argument('--font', default='')
  a = ap.parse_args()
  d = Path(a.dir)
  if a.cmd == 'mocap':
    from_takes(a.who, d)
  elif a.cmd == 'sketch':
    cmd_sketch(a.who, d, a.strip)
  elif a.cmd == 'reach':
    rows, u = reach_table(a.who)
    print(f'1 unit = {u:.3f} painting px')
    for r in rows:
      print(json.dumps(r, ensure_ascii=False))
  elif a.cmd == 'paint':
    cmd_paint(a.who, d, set(filter(None, a.only.split(','))), [int(x) for x in a.seeds.split(',')], a.master)
  elif a.cmd == 'gate':
    gate(a.who, d, set(filter(None, a.only.split(','))))
  elif a.cmd == 'compare':
    compare(a.who, d, a.out, json.loads(a.pairs), dict(p.split('=') for p in a.pick.split(',') if p), a.font or None)
  else:
    cmd_obey(a.who, d, dict(p.split('=') for p in a.pick.split(',') if p))


if __name__ == '__main__':
  main()
