  ICE = "ice",
  /** 砸寨 金刃 (讲堂试法): a sickle of light; a tap sends it straight, and it cuts wood through — 「金是镰」. */
  METAL = "metal",
  /** 砸寨 the basketball (今一 「你投一个给我看看」): no trick; it bounces. */
  BALL = "ball",
